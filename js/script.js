function initOpeningIntro() {
    const introOverlay = document.getElementById("intro-overlay");
    const introText = document.getElementById("intro-text");

    if (!introOverlay || !introText) return;

    // Persist per browser tab session (plays on tab open/reopen, skips on internal page navigation)
    if (sessionStorage.getItem("hasSeenIntro") === "true") {
        introOverlay.style.display = "none";
        document.body.style.overflow = "";
        return;
    }

    const greetings = [
        "Assalamu'alaikum",
        "Halo!",
        "こんにちは!",
        "안녕하세요!",
        "你好!",
        "مَرْحَبًا",
        "Halo!",
        "Sampurasun !",
        "Kula nuwun!",
        "Agakarebaa!",
        "Horas!",
        "Tabea!"
    ];

    let currentIndex = 0;
    document.body.style.overflow = "hidden";

    introText.textContent = greetings[0];
    currentIndex = 1;

    const intervalTime = 180; // Crisp fluid timing per word

    const greetingTimer = setInterval(() => {
        if (currentIndex < greetings.length) {
            introText.style.opacity = "0";
            introText.style.transform = "translateY(8px) scale(0.96)";

            setTimeout(() => {
                introText.textContent = greetings[currentIndex];
                introText.style.opacity = "1";
                introText.style.transform = "translateY(0px) scale(1)";
                currentIndex++;
            }, 50);
        } else {
            clearInterval(greetingTimer);
            setTimeout(() => {
                introOverlay.classList.add("intro-hidden");
                document.body.style.overflow = "";
                sessionStorage.setItem("hasSeenIntro", "true");
                if (typeof AOS !== "undefined") {
                    AOS.refresh();
                }
            }, 300);
        }
    }, intervalTime);
}

