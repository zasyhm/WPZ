function setLanguage(lang) {
    const currentLang = (lang === 'en' || lang === 'eng') ? 'en' : 'id';
    localStorage.setItem('preferred_lang', currentLang);
    document.documentElement.lang = currentLang;

    // Update language indicator texts
    document.querySelectorAll('.lang-text').forEach(el => {
        el.textContent = currentLang.toUpperCase();
    });

    // Update data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18nData[currentLang] && i18nData[currentLang][key]) {
            el.innerHTML = i18nData[currentLang][key];
        }
    });

    // Update data-i18n-placeholder elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (i18nData[currentLang] && i18nData[currentLang][key]) {
            el.setAttribute('placeholder', i18nData[currentLang][key]);
        }
    });

    // Update page card elements dynamically
    updateDynamicPageTranslations(currentLang);
}



function updateDynamicPageTranslations(currentLang) {
    // 1. Process all text elements (h2, h3, h4, p, span, button, a)
    const targets = document.querySelectorAll('h2, h3, h4, p, span, button, a');
    targets.forEach(el => {
        // Skip elements with specific data-i18n as setLanguage handles them directly
        if (el.hasAttribute('data-i18n')) return;

        // Skip elements containing complex children or icons only
        if (el.children.length > 1) return;

        const rawText = el.getAttribute('data-id-text') || el.textContent.trim();
        if (!rawText || rawText.length < 2) return;

        if (!el.getAttribute('data-id-text')) {
            el.setAttribute('data-id-text', rawText);
        }

        if (currentLang === 'en') {
            if (PHRASE_TRANSLATIONS[rawText]) {
                const icon = el.querySelector('i');
                if (icon) {
                    el.innerHTML = icon.outerHTML + ' ' + PHRASE_TRANSLATIONS[rawText].en;
                } else {
                    el.textContent = PHRASE_TRANSLATIONS[rawText].en;
                }
            } else if (rawText.includes('Foto')) {
                el.innerHTML = el.innerHTML.replace('Foto', 'Photo');
            } else if (rawText.includes('Desain')) {
                el.innerHTML = el.innerHTML.replace('Desain', 'Design');
            } else if (rawText.includes('Sertifikat')) {
                el.innerHTML = el.innerHTML.replace('Sertifikat', 'Certificate');
            } else if (rawText.includes('Juara 3')) {
                el.innerHTML = el.innerHTML.replace('Juara 3', '3rd Winner');
            } else if (rawText.includes('Juara 2')) {
                el.innerHTML = el.innerHTML.replace('Juara 2', '2nd Winner');
            } else if (rawText.includes('Lihat Sertifikat')) {
                el.innerHTML = el.innerHTML.replace('Lihat Sertifikat', 'View Certificate');
            }
        } else {
            const orig = el.getAttribute('data-id-text');
            if (orig) {
                const icon = el.querySelector('i');
                if (icon) {
                    el.innerHTML = icon.outerHTML + ' ' + orig;
                } else {
                    el.textContent = orig;
                }
            }
        }
    });
}



function toggleLanguage() {
    const current = localStorage.getItem('preferred_lang') || 'id';
    const nextLang = current === 'id' ? 'en' : 'id';

    // 1. Globe Icon Spin & Button Glow Animation
    const globes = document.querySelectorAll('.fa-globe');
    globes.forEach(g => {
        g.classList.remove('globe-spin');
        void g.offsetWidth;
        g.classList.add('globe-spin');
    });

    const langBtns = document.querySelectorAll('[onclick="toggleLanguage()"]');
    langBtns.forEach(btn => {
        btn.classList.remove('lang-btn-pulse');
        void btn.offsetWidth;
        btn.classList.add('lang-btn-pulse');
    });

    // 2. Matrix Blur & Fade Swap Effect on Text
    const textEls = document.querySelectorAll('[data-i18n], h1, h2, h3, h4, p, .project-item span, .filter-btn span');
    textEls.forEach(el => {
        el.classList.remove('lang-swap-effect');
        void el.offsetWidth;
        el.classList.add('lang-swap-effect');
    });

    // 3. Switch Language at midpoint of animation
    setTimeout(() => {
        setLanguage(nextLang);
        showLanguageToast(nextLang);
    }, 180);

    // 4. Remove transition class after completion
    setTimeout(() => {
        textEls.forEach(el => el.classList.remove('lang-swap-effect'));
    }, 500);
}

function showLanguageToast(lang) {
    let container = document.getElementById('lang-toast-wrap');
    if (!container) {
        container = document.createElement('div');
        container.id = 'lang-toast-wrap';
        container.className = 'lang-toast-container';
        document.body.appendChild(container);
    }

    const message = lang === 'en'
        ? '<i class="fa-solid fa-globe text-cyan-400 mr-1.5 animate-pulse"></i> Switched to <strong>English</strong>'
        : '<i class="fa-solid fa-globe text-cyan-400 mr-1.5 animate-pulse"></i> Dialihkan ke <strong>Bahasa Indonesia</strong>';

    container.innerHTML = `
        <div class="lang-toast-card">
            <span>${message}</span>
            <div class="lang-toast-bar"></div>
        </div>
    `;

    container.classList.remove('show');
    void container.offsetWidth;
    container.classList.add('show');

    clearTimeout(window.langToastTimer);
    window.langToastTimer = setTimeout(() => {
        container.classList.remove('show');
    }, 2000);
}


// Mobile Navigation Menu Toggle
function toggleMobileMenu() {
    const menu = document.getElementById('mobile-menu');
    const button = document.getElementById('mobile-menu-btn');
    if (!menu) return;

    const isExpanded = button ? button.getAttribute('aria-expanded') === 'true' : false;

    if (isExpanded) {
        menu.classList.add('max-h-0', 'opacity-0', 'pointer-events-none');
        menu.classList.remove('max-h-96', 'opacity-100', 'pointer-events-auto');
        if (button) button.setAttribute('aria-expanded', 'false');
    } else {
        menu.classList.remove('max-h-0', 'opacity-0', 'pointer-events-none');
        menu.classList.add('max-h-96', 'opacity-100', 'pointer-events-auto');
        if (button) button.setAttribute('aria-expanded', 'true');
    }
}

