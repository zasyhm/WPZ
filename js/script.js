function initLanyardPhysics(canvas) {
    const isSubfolder = window.location.pathname.includes('/html/') || window.location.pathname.includes('\\html\\');
    const candidatePaths = isSubfolder
        ? ['../assets/img/lanyard.jpg', 'assets/img/lanyard.jpg', '/assets/img/lanyard.jpg', './assets/img/lanyard.jpg']
        : ['assets/img/lanyard.jpg', '../assets/img/lanyard.jpg', '/assets/img/lanyard.jpg', './assets/img/lanyard.jpg'];

    if (typeof THREE !== 'undefined') {
        initThreeLanyard(canvas, candidatePaths);
    } else {
        init2DLanyard(canvas, candidatePaths);
    }
}

function loadCardImageWithFallback(candidatePaths, onLoadCallback) {
    let pathIndex = 0;

    function tryNextPath() {
        if (pathIndex >= candidatePaths.length) {
            console.error('[Lanyard] GAGAL memuat foto CV dari semua path kandidat:', candidatePaths);
            return;
        }
        const currentPath = candidatePaths[pathIndex];
        pathIndex++;

        const img = new Image();
        img.crossOrigin = 'Anonymous';
        img.onload = () => {
            console.log('[Lanyard] Foto CV berhasil dimuat dari path:', currentPath);
            onLoadCallback(img);
        };
        img.onerror = () => {
            console.warn('[Lanyard] Gagal memuat dari path (' + currentPath + '), mencoba path berikutnya...');
            tryNextPath();
        };
        img.src = currentPath;
    }

    tryNextPath();
}

function initThreeLanyard(canvas, candidatePaths) {
    const parent = canvas.parentElement;
    let width = parent.clientWidth || 320;
    let height = parent.clientHeight || 400;

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(45, width / height, 0.1, 1000);
    camera.position.set(0, 0.4, 6.8);

    const renderer = new THREE.WebGLRenderer({ canvas: canvas, alpha: true, antialias: true });
    renderer.setSize(width, height);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));

    const ambientLight = new THREE.AmbientLight(0xffffff, 0.95);
    scene.add(ambientLight);

    const dirLight = new THREE.DirectionalLight(0x06b6d4, 1.4);
    dirLight.position.set(5, 8, 5);
    scene.add(dirLight);

    const dirLight2 = new THREE.DirectionalLight(0xffffff, 0.7);
    dirLight2.position.set(-5, -5, 3);
    scene.add(dirLight2);

    // 1. TALI DIPENDEKIN: Titik atas diturunin (dari 4.4 jadi 3.5)
    const topAnchor = new THREE.Vector3(0, 3.5, 0);

    const cardGroup = new THREE.Group();

    // 2. KOTAK DIGEDEIN: Lebar dan tinggi ditambah
    const cardWidth = 3.4;  // Sebelumnya 2.65
    const cardHeight = 4.3; // Sebelumnya 3.35

    const cvCanvas = document.createElement('canvas');
    cvCanvas.width = 512;
    cvCanvas.height = 640;
    const ctx = cvCanvas.getContext('2d');

    function drawCardCanvas(img) {
        ctx.fillStyle = '#0f172a';
        ctx.fillRect(0, 0, 512, 640);

        if (img) {
            ctx.save();
            ctx.beginPath();
            if (typeof ctx.roundRect === 'function') {
                ctx.roundRect(6, 6, 500, 628, 28);
            } else {
                ctx.rect(6, 6, 500, 628);
            }
            ctx.clip();
            ctx.drawImage(img, 6, 6, 500, 628);
            ctx.restore();
        } else {
            ctx.fillStyle = '#1e293b';
            ctx.fillRect(6, 6, 500, 628);
        }

        ctx.lineWidth = 10;
        ctx.strokeStyle = '#06b6d4';
        ctx.beginPath();
        if (typeof ctx.roundRect === 'function') {
            ctx.roundRect(4, 4, 504, 632, 28);
        } else {
            ctx.rect(4, 4, 504, 632);
        }
        ctx.stroke();

        ctx.fillStyle = '#0b0f17';
        ctx.beginPath();
        ctx.arc(256, 36, 16, 0, Math.PI * 2);
        ctx.fill();
        ctx.lineWidth = 4;
        ctx.strokeStyle = '#38bdf8';
        ctx.stroke();
    }

    drawCardCanvas(null);

    const customTex = new THREE.CanvasTexture(cvCanvas);
    customTex.minFilter = THREE.LinearFilter;
    customTex.magFilter = THREE.LinearFilter;

    const cardGeo = new THREE.PlaneGeometry(cardWidth, cardHeight);
    const cardMat = new THREE.MeshStandardMaterial({
        map: customTex,
        roughness: 0.35,
        metalness: 0.25,
        side: THREE.DoubleSide
    });

    const cardMesh = new THREE.Mesh(cardGeo, cardMat);
    cardGroup.add(cardMesh);

    // 3. POSISI CINCIN DISESUAIKAN karena kotaknya makin tinggi
    const ringGeo = new THREE.TorusGeometry(0.15, 0.038, 16, 32);
    const ringMat = new THREE.MeshStandardMaterial({ color: 0x38bdf8, metalness: 0.85, roughness: 0.15 });
    const ringMesh = new THREE.Mesh(ringGeo, ringMat);
    ringMesh.position.set(0, 2.2, 0); // Sebelumnya 1.72
    cardGroup.add(ringMesh);

    scene.add(cardGroup);

    // Muat gambar dengan fallback otomatis
    loadCardImageWithFallback(candidatePaths, (loadedImg) => {
        drawCardCanvas(loadedImg);
        customTex.needsUpdate = true;
    });

    // 4. TALI DIPENDEKIN: Posisi awal kartu dinaikin (dari -0.4 jadi 0.5)
    const restPos = new THREE.Vector3(0, 0.5, 0);
    cardGroup.position.copy(restPos);

    let lanyardLine;
    function updateLanyardRope() {
        if (lanyardLine) scene.remove(lanyardLine);

        // Ujung tali ikutan naik menyesuaikan kotak
        const cardClipPos = new THREE.Vector3(cardGroup.position.x, cardGroup.position.y + 2.15, cardGroup.position.z);
        const midPoint = new THREE.Vector3(
            (topAnchor.x + cardClipPos.x) * 0.5,
            (topAnchor.y + cardClipPos.y) * 0.5 - 0.2,
            (topAnchor.z + cardClipPos.z) * 0.5
        );

        const curve = new THREE.QuadraticBezierCurve3(topAnchor, midPoint, cardClipPos);
        const points = curve.getPoints(24);
        const ropeGeo = new THREE.BufferGeometry().setFromPoints(points);
        const ropeMat = new THREE.LineDashedMaterial({
            color: 0x06b6d4,
            linewidth: 3,
            scale: 1,
            dashSize: 0.1,
            gapSize: 0.05
        });
        lanyardLine = new THREE.Line(ropeGeo, ropeMat);
        lanyardLine.computeLineDistances();
        scene.add(lanyardLine);
    }

    updateLanyardRope();

    let isDragging = false;
    let velocity = new THREE.Vector3(0, 0, 0);
    const raycaster = new THREE.Raycaster();
    const mouse = new THREE.Vector2();
    const plane = new THREE.Plane(new THREE.Vector3(0, 0, 1), 0);

    function getMouseNDCPosition(e) {
        const rect = canvas.getBoundingClientRect();
        const clientX = e.touches ? e.touches[0].clientX : e.clientX;
        const clientY = e.touches ? e.touches[0].clientY : e.clientY;
        mouse.x = ((clientX - rect.left) / rect.width) * 2 - 1;
        mouse.y = -((clientY - rect.top) / rect.height) * 2 + 1;
    }

    let lastTime = performance.now();
    let isCanvasVisible = true;
    let animFrameId = null;
    let isAnimating = false;

    function startLoop() {
        if (!isAnimating && isCanvasVisible) {
            isAnimating = true;
            lastTime = performance.now();
            if (animFrameId) cancelAnimationFrame(animFrameId);
            animFrameId = requestAnimationFrame(animate);
        }
    }

    function onPointerDown(e) {
        getMouseNDCPosition(e);
        raycaster.setFromCamera(mouse, camera);
        isDragging = true;
        canvas.style.cursor = 'grabbing';
        velocity.set(0, 0, 0);
        startLoop();
    }

    function onPointerMove(e) {
        if (!isDragging) return;
        getMouseNDCPosition(e);
        raycaster.setFromCamera(mouse, camera);
        const target = new THREE.Vector3();
        raycaster.ray.intersectPlane(plane, target);

        const maxRadius = 2.4;
        const dist = target.distanceTo(restPos);
        if (dist > maxRadius) {
            target.sub(restPos).normalize().multiplyScalar(maxRadius).add(restPos);
        }

        const prevPos = cardGroup.position.clone();
        cardGroup.position.copy(target);
        velocity.subVectors(cardGroup.position, prevPos).multiplyScalar(15);

        cardGroup.rotation.z = -cardGroup.position.x * 0.25;
        cardGroup.rotation.x = (cardGroup.position.y - restPos.y) * 0.15;
        cardGroup.rotation.y = cardGroup.position.x * 0.2;

        updateLanyardRope();
        startLoop();
    }

    function onPointerUp() {
        if (isDragging) {
            isDragging = false;
            canvas.style.cursor = 'grab';
        }
    }

    canvas.addEventListener('mousedown', onPointerDown);
    window.addEventListener('mousemove', onPointerMove, { passive: true });
    window.addEventListener('mouseup', onPointerUp);

    canvas.addEventListener('touchstart', onPointerDown, { passive: true });
    window.addEventListener('touchmove', onPointerMove, { passive: true });
    window.addEventListener('touchend', onPointerUp);

    function animate() {
        if (!isCanvasVisible || !isAnimating) {
            isAnimating = false;
            return;
        }

        const now = performance.now();
        const dt = Math.min((now - lastTime) / 1000, 0.05);
        lastTime = now;

        let keepAnimating = isDragging;

        if (!isDragging) {
            const stiffness = 38.0;
            const damping = 4.8;

            const springForceX = -stiffness * (cardGroup.position.x - restPos.x);
            const springForceY = -stiffness * (cardGroup.position.y - restPos.y);

            velocity.x += (springForceX - damping * velocity.x) * dt;
            velocity.y += (springForceY - damping * velocity.y) * dt;

            cardGroup.position.x += velocity.x * dt;
            cardGroup.position.y += velocity.y * dt;

            const targetRotZ = -cardGroup.position.x * 0.35 - velocity.x * 0.04;
            const targetRotX = (cardGroup.position.y - restPos.y) * 0.2;
            const targetRotY = velocity.x * 0.05;

            cardGroup.rotation.z += (targetRotZ - cardGroup.rotation.z) * 0.15;
            cardGroup.rotation.x += (targetRotX - cardGroup.rotation.x) * 0.15;
            cardGroup.rotation.y += (targetRotY - cardGroup.rotation.y) * 0.15;

            updateLanyardRope();

            const distFromRest = cardGroup.position.distanceTo(restPos);
            if (distFromRest > 0.005 || velocity.lengthSq() > 0.001) {
                keepAnimating = true;
            } else {
                cardGroup.position.copy(restPos);
                velocity.set(0, 0, 0);
                cardGroup.rotation.set(0, 0, 0);
                updateLanyardRope();
            }
        }

        renderer.render(scene, camera);

        if (keepAnimating && isCanvasVisible) {
            animFrameId = requestAnimationFrame(animate);
        } else {
            isAnimating = false;
        }
    }

    if ('IntersectionObserver' in window) {
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                isCanvasVisible = entry.isIntersecting;
                if (isCanvasVisible) {
                    startLoop();
                } else {
                    isAnimating = false;
                    if (animFrameId) cancelAnimationFrame(animFrameId);
                }
            });
        }, { threshold: 0.05 });
        observer.observe(canvas);
    } else {
        startLoop();
    }

    window.addEventListener('resize', () => {
        if (!parent) return;
        width = parent.clientWidth || 300;
        height = parent.clientHeight || 360;
        camera.aspect = width / height;
        camera.updateProjectionMatrix();
        renderer.setSize(width, height);
    });
}

function init2DLanyard(canvas, candidatePaths) {
    const ctx = canvas.getContext('2d');
    const parent = canvas.parentElement;
    let width = canvas.width = parent.clientWidth || 300;
    let height = canvas.height = parent.clientHeight || 360;

    let img = null;
    loadCardImageWithFallback(candidatePaths, (loadedImg) => {
        img = loadedImg;
    });

    let restX = width / 1;
    // Tali versi 2D dipendekin
    let restY = height / 2 - 20;
    let cardX = restX;
    let cardY = restY;
    let velX = 0;
    let velY = 0;
    let isDragging = false;

    function draw() {
        ctx.clearRect(0, 0, width, height);

        // Rope
        ctx.beginPath();
        ctx.moveTo(width / 2, 0);
        ctx.quadraticCurveTo((width / 1 + cardX) / 1, (0 + cardY - 120) / 2, cardX, cardY - 140);
        ctx.strokeStyle = '#06b6d4';
        ctx.lineWidth = 1;
        ctx.setLineDash([6, 4]);
        ctx.stroke();
        ctx.setLineDash([]);

        // Card Frame
        ctx.save();
        ctx.translate(cardX, cardY);
        const rot = -(cardX - restX) * 0.002;
        ctx.rotate(rot);

        ctx.fillStyle = '#0f172a';
        ctx.strokeStyle = 'rgba(5, 125, 146, 0.8)';
        ctx.lineWidth = 4;
        ctx.beginPath();
        if (ctx.roundRect) {
            ctx.roundRect(-120, -140, 240, 280, 24);
        } else {
            ctx.rect(-120, -140, 240, 280);
        }
        ctx.fill();
        ctx.stroke();

        // Foto CV — cek img.complete DAN img.naturalWidth > 0 agar tidak render gambar rusak
        if (img && img.complete && img.naturalWidth > 0) {
            ctx.save();
            ctx.beginPath();
            if (ctx.roundRect) {
                ctx.roundRect(-112, -132, 224, 264, 18);
            } else {
                ctx.rect(-112, -132, 224, 264);
            }
            ctx.clip();
            ctx.drawImage(img, -112, -132, 224, 264);
            ctx.restore();
        }

        ctx.restore();

        let keepAnimating = isDragging;
        if (!isDragging) {
            const fx = -0.08 * (cardX - restX);
            const fy = -0.08 * (cardY - restY);
            velX = (velX + fx) * 0.88;
            velY = (velY + fy) * 0.88;
            cardX += velX;
            cardY += velY;

            if (Math.abs(cardX - restX) > 0.1 || Math.abs(cardY - restY) > 0.1 || Math.abs(velX) > 0.05 || Math.abs(velY) > 0.05) {
                keepAnimating = true;
            } else {
                cardX = restX;
                cardY = restY;
                velX = 0;
                velY = 0;
            }
        }

        if (isCanvasVisible && keepAnimating) {
            animFrameId = requestAnimationFrame(draw);
        } else {
            isAnimating = false;
        }
    }

    let isCanvasVisible = true;
    let animFrameId = null;
    let isAnimating = false;

    function startLoop2D() {
        if (!isAnimating && isCanvasVisible) {
            isAnimating = true;
            if (animFrameId) cancelAnimationFrame(animFrameId);
            animFrameId = requestAnimationFrame(draw);
        }
    }

    if ('IntersectionObserver' in window) {
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                isCanvasVisible = entry.isIntersecting;
                if (isCanvasVisible) {
                    startLoop2D();
                } else {
                    isAnimating = false;
                    if (animFrameId) cancelAnimationFrame(animFrameId);
                }
            });
        }, { threshold: 0.05 });
        observer.observe(canvas);
    }

    // Mouse events
    canvas.addEventListener('mousedown', () => { isDragging = true; startLoop2D(); });
    window.addEventListener('mousemove', (e) => {
        if (!isDragging) return;
        const rect = canvas.getBoundingClientRect();
        cardX = e.clientX - rect.left;
        cardY = e.clientY - rect.top;
        startLoop2D();
    }, { passive: true });
    window.addEventListener('mouseup', () => { isDragging = false; });

    // Touch events (mobile support)
    canvas.addEventListener('touchstart', (e) => {
        isDragging = true;
        e.preventDefault();
    }, { passive: false });
    window.addEventListener('touchmove', (e) => {
        if (!isDragging) return;
        const rect = canvas.getBoundingClientRect();
        cardX = e.touches[0].clientX - rect.left;
        cardY = e.touches[0].clientY - rect.top;
    }, { passive: true });
    window.addEventListener('touchend', () => { isDragging = false; });

    // Resize handler
    window.addEventListener('resize', () => {
        width = canvas.width = parent.clientWidth || 300;
        height = canvas.height = parent.clientHeight || 360;
        restX = width / 2;
        restY = height / 2 - 20;
    });

    draw();
}

